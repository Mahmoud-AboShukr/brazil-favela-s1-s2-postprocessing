def load_config(config_path: Path) -> Dict[str, Any]:
    if not config_path.exists():
        raise FileNotFoundError(f"Config file not found: {config_path}")

    with config_path.open("r", encoding="utf-8") as f:
        cfg = yaml.safe_load(f) or {}

    if "output_root" not in cfg:
        raise KeyError("Missing required key in config: output_root")

    return cfg


def ensure_dir(path: Path) -> None:
    path.mkdir(parents=True, exist_ok=True)


def normalize_city_name(value: str) -> str:
    return (
        str(value)
        .strip()
        .lower()
        .replace("-", "_")
        .replace(" ", "_")
        .replace("__", "_")
    )


def discover_gpt_path(cfg: Dict[str, Any], cli_gpt_path: Optional[Path]) -> Optional[Path]:
    candidates: List[Path] = []

    if cli_gpt_path:
        candidates.append(cli_gpt_path)

    env_gpt = os.environ.get("SNAP_GPT")
    if env_gpt:
        candidates.append(Path(env_gpt))

    if cfg.get("snap_gpt_path"):
        candidates.append(Path(str(cfg["snap_gpt_path"])))

    which_gpt = shutil.which("gpt") or shutil.which("gpt.exe")
    if which_gpt:
        candidates.append(Path(which_gpt))

    candidates.extend(
        [
            Path("C:/Program Files/esa-snap/bin/gpt.exe"),
            Path("C:/Program Files/snap/bin/gpt.exe"),
            Path("C:/Program Files/ESA SNAP/bin/gpt.exe"),
            Path("/usr/local/snap/bin/gpt"),
            Path("/opt/snap/bin/gpt"),
            Path("/usr/bin/gpt"),
        ]
    )

    for candidate in candidates:
        try:
            if candidate.exists() and candidate.is_file():
                return candidate
        except OSError:
            continue

    return None


def load_safe_inventory(inventory_path: Path) -> pd.DataFrame:
    if not inventory_path.exists():
        raise FileNotFoundError(
            f"SAFE inventory not found: {inventory_path}\n"
            "Run 07a first:\n"
            "python src/favela_postprocessing/07a_build_s1_safe_inventory.py --config configs/default.yaml"
        )

    df = pd.read_csv(inventory_path)

    required = ["city", "status", "safe_path", "safe_is_valid_for_snap"]
    missing = [col for col in required if col not in df.columns]

    if missing:
        raise KeyError(
            f"SAFE inventory is missing required columns: {missing}\n"
            f"Inventory path: {inventory_path}"
        )

    df["city"] = df["city"].map(normalize_city_name)

    return df


def filter_inventory(
    df: pd.DataFrame,
    selected_cities: Optional[Sequence[str]],
    pilot_only: bool,
) -> pd.DataFrame:
    out = df.copy()

    if pilot_only:
        cities = set(PILOT_CITIES)
        out = out[out["city"].isin(cities)]

    if selected_cities:
        cities = set(normalize_city_name(city) for city in selected_cities)
        out = out[out["city"].isin(cities)]

    out = out.sort_values("city").reset_index(drop=True)

    return out


def bool_from_any(value: Any) -> bool:
    if isinstance(value, bool):
        return value

    if isinstance(value, (int, float)):
        return bool(value)

    value_str = str(value).strip().lower()

    return value_str in {"true", "1", "yes", "y"}


