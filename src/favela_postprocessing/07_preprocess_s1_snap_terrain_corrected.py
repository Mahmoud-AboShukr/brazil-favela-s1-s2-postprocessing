#!/usr/bin/env python3
"""
SNAP-based Sentinel-1 GRD terrain-corrected preprocessing.

This script implements the Sentinel-1 part of:

    Instance B: standard remote-sensing dataset

It expects full Sentinel-1 SAFE products, not only VV.tif / VH.tif files.

Input requirements
------------------
1. A SAFE inventory generated by:

    src/favela_postprocessing/07a_build_s1_safe_inventory.py

Expected inventory path:

    <output_root>/metadata/s1_safe_inventory.csv

2. Full Sentinel-1 SAFE products for the cities to process.

3. ESA SNAP installed, with GPT available either:
    - in PATH as gpt / gpt.exe
    - via --gpt-path
    - via environment variable SNAP_GPT
    - via config key snap_gpt_path

4. A Sentinel-2 reference grid, preferably from:

    <output_root>/dataset_instances/instance_B_standard_rs/s2/<city>/
        <city>_s2_12bands_reflectance_10m.tif

Fallback reference:

    <output_root>/s2_final/<city>/<city>_s2_allbands_10m.tif

Processing chain
----------------
For each SAFE-ready city:

    Read
    Apply-Orbit-File
    ThermalNoiseRemoval
    Calibration to Sigma0 VV/VH, linear scale
    Terrain-Correction
    Write temporary GeoTIFF

Then Python/rasterio:

    Read SNAP terrain-corrected output
    Extract VV and VH
    Align exactly to the Sentinel-2 grid
    Convert linear Sigma0 to dB
    Create VV_minus_VH_dB
    Save final 3-band GeoTIFF

Output
------
Final aligned S1 SNAP product:

    <output_root>/dataset_instances/instance_B_standard_rs/s1_snap/<city>/
        <city>_s1_snap_vv_vh_vvdiff_10m_aligned.tif

Bands:
    1. VV_dB
    2. VH_dB
    3. VV_minus_VH_dB

QC:
    <output_root>/qc/s1_snap_terrain_corrected_qc.csv

Examples
--------
Dry run all cities:

    python src/favela_postprocessing/07_preprocess_s1_snap_terrain_corrected.py --config configs/default.yaml --dry-run

Dry run pilot cities:

    python src/favela_postprocessing/07_preprocess_s1_snap_terrain_corrected.py --config configs/default.yaml --pilot-only --dry-run

Run one city after SAFE is available:

    python src/favela_postprocessing/07_preprocess_s1_snap_terrain_corrected.py --config configs/default.yaml --city rio_de_janeiro --gpt-path "C:/Program Files/esa-snap/bin/gpt.exe"

Force overwrite:

    python src/favela_postprocessing/07_preprocess_s1_snap_terrain_corrected.py --config configs/default.yaml --city rio_de_janeiro --overwrite
"""

