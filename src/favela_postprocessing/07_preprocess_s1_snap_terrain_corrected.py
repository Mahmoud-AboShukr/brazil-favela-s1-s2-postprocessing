def make_xml_text(element: ET.Element) -> str:
    rough = ET.tostring(element, encoding="utf-8")
    parsed = xml.dom.minidom.parseString(rough)
    return parsed.toprettyxml(indent="  ")


def add_text(parent: ET.Element, tag: str, text: Any) -> ET.Element:
    elem = ET.SubElement(parent, tag)
    elem.text = str(text)
    return elem


def add_node(
    graph: ET.Element,
    node_id: str,
    operator: str,
    source_ref: Optional[str],
    parameters: Dict[str, Any],
) -> ET.Element:
    node = ET.SubElement(graph, "node", {"id": node_id})
    add_text(node, "operator", operator)

    sources = ET.SubElement(node, "sources")
    if source_ref is not None:
        add_text(sources, "sourceProduct", source_ref).set("refid", source_ref)

    params = ET.SubElement(node, "parameters")
    for key, value in parameters.items():
        add_text(params, key, value)

    return node


def build_snap_graph_xml(
    safe_path: Path,
    snap_output_path: Path,
    dem_name: str,
    target_resolution: float,
    polarizations: str,
) -> str:
    """
    Build a SNAP GPT XML graph.

    The graph writes linear Sigma0 terrain-corrected VV/VH to GeoTIFF.
    Python then converts to dB and aligns exactly to the S2 grid.
    """
    graph = ET.Element("graph", {"id": "S1_GRD_TC"})
    add_text(graph, "version", "1.0")

    add_node(
        graph=graph,
        node_id="Read",
        operator="Read",
        source_ref=None,
        parameters={
            "file": str(safe_path),
        },
    )

    add_node(
        graph=graph,
        node_id="Apply-Orbit-File",
        operator="Apply-Orbit-File",
        source_ref="Read",
        parameters={
            "orbitType": "Sentinel Precise (Auto Download)",
            "polyDegree": "3",
            "continueOnFail": "true",
        },
    )

    add_node(
        graph=graph,
        node_id="ThermalNoiseRemoval",
        operator="ThermalNoiseRemoval",
        source_ref="Apply-Orbit-File",
        parameters={
            "selectedPolarisations": polarizations,
            "removeThermalNoise": "true",
            "reIntroduceThermalNoise": "false",
        },
    )

    add_node(
        graph=graph,
        node_id="Calibration",
        operator="Calibration",
        source_ref="ThermalNoiseRemoval",
        parameters={
            "sourceBands": "",
            "auxFile": "Product Auxiliary File",
            "externalAuxFile": "",
            "outputImageInComplex": "false",
            "outputImageScaleInDb": "false",
            "createGammaBand": "false",
            "createBetaBand": "false",
            "selectedPolarisations": polarizations,
            "outputSigmaBand": "true",
            "outputGammaBand": "false",
            "outputBetaBand": "false",
        },
    )

    add_node(
        graph=graph,
        node_id="Terrain-Correction",
        operator="Terrain-Correction",
        source_ref="Calibration",
        parameters={
            "sourceBands": "Sigma0_VV,Sigma0_VH",
            "demName": dem_name,
            "externalDEMFile": "",
            "externalDEMNoDataValue": "0.0",
            "externalDEMApplyEGM": "true",
            "demResamplingMethod": "BILINEAR_INTERPOLATION",
            "imgResamplingMethod": "BILINEAR_INTERPOLATION",
            "pixelSpacingInMeter": str(target_resolution),
            "pixelSpacingInDegree": "0.0",
            "mapProjection": "",
            "alignToStandardGrid": "false",
            "standardGridOriginX": "0.0",
            "standardGridOriginY": "0.0",
            "nodataValueAtSea": "false",
            "saveDEM": "false",
            "saveLatLon": "false",
            "saveIncidenceAngleFromEllipsoid": "false",
            "saveLocalIncidenceAngle": "false",
            "saveProjectedLocalIncidenceAngle": "false",
            "saveSelectedSourceBand": "true",
            "outputComplex": "false",
            "applyRadiometricNormalization": "false",
            "saveSigmaNought": "false",
            "saveGammaNought": "false",
            "saveBetaNought": "false",
            "incidenceAngleForSigma0": "Use projected local incidence angle from DEM",
            "incidenceAngleForGamma0": "Use projected local incidence angle from DEM",
            "auxFile": "Latest Auxiliary File",
        },
    )

    add_node(
        graph=graph,
        node_id="Write",
        operator="Write",
        source_ref="Terrain-Correction",
        parameters={
            "file": str(snap_output_path),
            "formatName": "GeoTIFF-BigTIFF",
        },
    )

    return make_xml_text(graph)


def write_snap_graph(
    graph_path: Path,
    safe_path: Path,
    snap_output_path: Path,
    dem_name: str,
    target_resolution: float,
    polarizations: str,
) -> None:
    ensure_dir(graph_path.parent)
    ensure_dir(snap_output_path.parent)

    xml_text = build_snap_graph_xml(
        safe_path=safe_path,
        snap_output_path=snap_output_path,
        dem_name=dem_name,
        target_resolution=target_resolution,
        polarizations=polarizations,
    )

    graph_path.write_text(xml_text, encoding="utf-8")


def run_snap_gpt(
    gpt_path: Path,
    graph_path: Path,
    snap_cache: Optional[str],
) -> Tuple[int, str, str]:
    cmd = [str(gpt_path), str(graph_path)]

    if snap_cache:
        cmd.extend(["-c", snap_cache])

    proc = subprocess.run(
        cmd,
        check=False,
        capture_output=True,
        text=True,
    )

    return proc.returncode, proc.stdout, proc.stderr


def find_band_index_by_name(
    src: rasterio.io.DatasetReader,
    wanted: str,
    fallback_index: int,
) -> int:
    wanted_lower = wanted.lower()

    for index, desc in enumerate(src.descriptions, start=1):
        if desc and wanted_lower in desc.lower():
            return index

    for index in range(1, src.count + 1):
        tags = src.tags(index)
        text = " ".join(str(v) for v in tags.values()).lower()
        if wanted_lower in text:
            return index

    if src.count >= fallback_index:
        return fallback_index

    raise RuntimeError(
        f"Could not find {wanted} band in SNAP output. "
        f"Band count={src.count}, descriptions={src.descriptions}"
    )


def linear_to_db(
    arr: np.ndarray,
    nodata: float,
    min_linear: float,
) -> np.ndarray:
    out = np.full(arr.shape, nodata, dtype="float32")

    valid = np.isfinite(arr) & (arr > 0)

    if valid.any():
        clipped = np.maximum(arr[valid].astype("float32", copy=False), np.float32(min_linear))
        out[valid] = 10.0 * np.log10(clipped)

    return out


def array_stats(arr: np.ndarray, nodata: float, band_name: str) -> BandStats:
    valid = np.isfinite(arr) & (arr != nodata)
    invalid = ~valid

    valid_count = int(valid.sum())
    invalid_count = int(invalid.sum())

    if valid_count == 0:
        return BandStats(
            band_name=band_name,
            valid_count=0,
            invalid_count=invalid_count,
            min_value=math.nan,
            max_value=math.nan,
            mean_value=math.nan,
            std_value=math.nan,
            p2_value=math.nan,
            p98_value=math.nan,
        )

    values = arr[valid].astype("float32", copy=False)

    return BandStats(
        band_name=band_name,
        valid_count=valid_count,
        invalid_count=invalid_count,
        min_value=float(np.min(values)),
        max_value=float(np.max(values)),
        mean_value=float(np.mean(values)),
        std_value=float(np.std(values)),
        p2_value=float(np.percentile(values, 2)),
        p98_value=float(np.percentile(values, 98)),
    )


def make_temp_output_path(final_path: Path) -> Path:
    ensure_dir(final_path.parent)

    handle = tempfile.NamedTemporaryFile(
        prefix=f".{final_path.stem}_",
        suffix=".tmp.tif",
        dir=final_path.parent,
        delete=False,
    )
    temp_path = Path(handle.name)
    handle.close()

    return temp_path


def align_snap_to_s2_and_write(
    city: str,
    snap_output_path: Path,
    s2_reference_path: Path,
    final_output_path: Path,
    compress: bool,
    overwrite: bool,
    min_linear: float = DEFAULT_MIN_LINEAR_BACKSCATTER,
    output_nodata: float = DEFAULT_OUTPUT_NODATA,
) -> List[Dict[str, Any]]:
    if final_output_path.exists() and not overwrite:
        return [
            {
                "city": city,
                "status": "SKIPPED_EXISTS",
                "snap_output_path": str(snap_output_path),
                "s2_reference_path": str(s2_reference_path),
                "final_output_path": str(final_output_path),
            }
        ]

    if not snap_output_path.exists():
        return [
            {
                "city": city,
                "status": "FAILED_MISSING_SNAP_OUTPUT",
                "snap_output_path": str(snap_output_path),
                "s2_reference_path": str(s2_reference_path),
                "final_output_path": str(final_output_path),
            }
        ]

    temp_path: Optional[Path] = None

    try:
        with rasterio.open(s2_reference_path) as s2_ref:
            dst_crs = s2_ref.crs
            dst_transform = s2_ref.transform
            dst_height = s2_ref.height
            dst_width = s2_ref.width

            if dst_crs is None:
                raise RuntimeError(f"S2 reference has no CRS: {s2_reference_path}")

            with rasterio.open(snap_output_path) as src:
                if src.crs is None:
                    raise RuntimeError(f"SNAP output has no CRS: {snap_output_path}")

                vv_index = find_band_index_by_name(src, "VV", fallback_index=1)
                vh_index = find_band_index_by_name(src, "VH", fallback_index=2)

                vv_linear_aligned = np.full(
                    (dst_height, dst_width),
                    np.nan,
                    dtype="float32",
                )
                vh_linear_aligned = np.full(
                    (dst_height, dst_width),
                    np.nan,
                    dtype="float32",
                )

                src_nodata = src.nodata

                reproject(
                    source=rasterio.band(src, vv_index),
                    destination=vv_linear_aligned,
                    src_transform=src.transform,
                    src_crs=src.crs,
                    src_nodata=src_nodata,
                    dst_transform=dst_transform,
                    dst_crs=dst_crs,
                    dst_nodata=np.nan,
                    resampling=Resampling.bilinear,
                )

                reproject(
                    source=rasterio.band(src, vh_index),
                    destination=vh_linear_aligned,
                    src_transform=src.transform,
                    src_crs=src.crs,
                    src_nodata=src_nodata,
                    dst_transform=dst_transform,
                    dst_crs=dst_crs,
                    dst_nodata=np.nan,
                    resampling=Resampling.bilinear,
                )

                vv_db = linear_to_db(vv_linear_aligned, output_nodata, min_linear)
                vh_db = linear_to_db(vh_linear_aligned, output_nodata, min_linear)

                both_valid = (
                    np.isfinite(vv_db)
                    & np.isfinite(vh_db)
                    & (vv_db != output_nodata)
                    & (vh_db != output_nodata)
                )

                vv_minus_vh = np.full((dst_height, dst_width), output_nodata, dtype="float32")
                vv_minus_vh[both_valid] = vv_db[both_valid] - vh_db[both_valid]

                output_stack = np.stack([vv_db, vh_db, vv_minus_vh], axis=0).astype("float32")

                profile = s2_ref.profile.copy()
                profile.update(
                    driver="GTiff",
                    dtype="float32",
                    count=3,
                    nodata=output_nodata,
                    BIGTIFF="IF_SAFER",
                )
                profile.pop("photometric", None)

                if compress:
                    profile.update(compress="DEFLATE", predictor=3)
                else:
                    profile.pop("compress", None)
                    profile.pop("predictor", None)

                if dst_width >= 512 and dst_height >= 512:
                    profile.update(tiled=True, blockxsize=512, blockysize=512)

                temp_path = make_temp_output_path(final_output_path)

                with rasterio.open(temp_path, "w", **profile) as dst:
                    dst.write(output_stack)
                    dst.set_band_description(1, "VV_dB")
                    dst.set_band_description(2, "VH_dB")
                    dst.set_band_description(3, "VV_minus_VH_dB")
                    dst.update_tags(
                        city=city,
                        processing_script=SCRIPT_NAME,
                        dataset_instance=INSTANCE_NAME,
                        source_snap_output=str(snap_output_path),
                        s2_reference_grid=str(s2_reference_path),
                        output_units="dB",
                        bands="VV_dB,VH_dB,VV_minus_VH_dB",
                    )

                temp_path.replace(final_output_path)

                stats = [
                    array_stats(vv_db, output_nodata, "VV_dB"),
                    array_stats(vh_db, output_nodata, "VH_dB"),
                    array_stats(vv_minus_vh, output_nodata, "VV_minus_VH_dB"),
                ]

                rows: List[Dict[str, Any]] = []

                for band_number, stat in enumerate(stats, start=1):
                    rows.append(
                        {
                            "city": city,
                            "status": "OK",
                            "band": band_number,
                            "band_name": stat.band_name,
                            "snap_output_path": str(snap_output_path),
                            "s2_reference_path": str(s2_reference_path),
                            "final_output_path": str(final_output_path),
                            "snap_band_vv_index": vv_index,
                            "snap_band_vh_index": vh_index,
                            "snap_crs": str(src.crs),
                            "s2_crs": str(dst_crs),
                            "output_crs": str(dst_crs),
                            "output_width": dst_width,
                            "output_height": dst_height,
                            "output_transform": str(dst_transform),
                            "output_nodata": output_nodata,
                            "valid_count": stat.valid_count,
                            "invalid_count": stat.invalid_count,
                            "min": stat.min_value,
                            "max": stat.max_value,
                            "mean": stat.mean_value,
                            "std": stat.std_value,
                            "p2": stat.p2_value,
                            "p98": stat.p98_value,
                        }
                    )

                return rows

    except Exception as exc:
        if temp_path is not None and temp_path.exists():
            temp_path.unlink(missing_ok=True)

        return [
            {
                "city": city,
                "status": "FAILED_ALIGN_OR_WRITE",
                "snap_output_path": str(snap_output_path),
                "s2_reference_path": str(s2_reference_path),
                "final_output_path": str(final_output_path),
                "error": repr(exc),
            }
        ]


def process_city(
    row: pd.Series,
    output_root: Path,
    gpt_path: Optional[Path],
    compress: bool,
    overwrite: bool,
    dry_run: bool,
    keep_snap_temp: bool,
    dem_name: str,
    target_resolution: float,
    polarizations: str,
    snap_cache: Optional[str],
) -> List[Dict[str, Any]]:
    city = normalize_city_name(row["city"])

    final_output_path = get_final_output_path(output_root, city)
    graph_path = get_graph_path(output_root, city)
    snap_output_path = get_snap_temp_output_path(output_root, city)
    s2_reference_path = get_s2_reference_path(output_root, city)

    inventory_status = str(row.get("status", ""))
    safe_is_valid = bool_from_any(row.get("safe_is_valid_for_snap", False))
    safe_path_value = str(row.get("safe_path", "")).strip()
    safe_path = Path(safe_path_value) if safe_path_value else None

    base_row = {
        "city": city,
        "inventory_status": inventory_status,
        "safe_path": safe_path_value,
        "graph_path": str(graph_path),
        "snap_output_path": str(snap_output_path),
        "final_output_path": str(final_output_path),
        "s2_reference_path": str(s2_reference_path) if s2_reference_path else "",
    }

    if final_output_path.exists() and not overwrite:
        out = dict(base_row)
        out.update({"status": "SKIPPED_EXISTS"})
        return [out]

    if s2_reference_path is None:
        out = dict(base_row)
        out.update(
            {
                "status": "SKIPPED_MISSING_S2_REFERENCE",
                "recommendation": "Create/check S2 finalized or instance_B_standard_rs S2 product first.",
            }
        )
        return [out]

    if not safe_is_valid or safe_path is None or not safe_path.exists():
        out = dict(base_row)
        out.update(
            {
                "status": "SKIPPED_NO_VALID_SAFE",
                "recommendation": (
                    "Download or locate the full Sentinel-1 .SAFE product, then rerun 07a inventory."
                ),
            }
        )
        return [out]

    if gpt_path is None:
        out = dict(base_row)
        out.update(
            {
                "status": "SKIPPED_MISSING_SNAP_GPT",
                "recommendation": (
                    "Install ESA SNAP and pass --gpt-path, or set SNAP_GPT environment variable."
                ),
            }
        )
        return [out]

    if dry_run:
        out = dict(base_row)
        out.update(
            {
                "status": "DRY_RUN_READY",
                "gpt_path": str(gpt_path),
                "dem_name": dem_name,
                "target_resolution": target_resolution,
                "polarizations": polarizations,
            }
        )
        return [out]

    try:
        write_snap_graph(
            graph_path=graph_path,
            safe_path=safe_path,
            snap_output_path=snap_output_path,
            dem_name=dem_name,
            target_resolution=target_resolution,
            polarizations=polarizations,
        )

        return_code, stdout, stderr = run_snap_gpt(
            gpt_path=gpt_path,
            graph_path=graph_path,
            snap_cache=snap_cache,
        )

        stdout_path = graph_path.with_suffix(".stdout.txt")
        stderr_path = graph_path.with_suffix(".stderr.txt")

        stdout_path.write_text(stdout or "", encoding="utf-8")
        stderr_path.write_text(stderr or "", encoding="utf-8")

        if return_code != 0:
            out = dict(base_row)
            out.update(
                {
                    "status": "FAILED_SNAP_GPT",
                    "gpt_path": str(gpt_path),
                    "gpt_return_code": return_code,
                    "gpt_stdout_path": str(stdout_path),
                    "gpt_stderr_path": str(stderr_path),
                    "error": "SNAP GPT returned a non-zero exit code.",
                }
            )
            return [out]

        rows = align_snap_to_s2_and_write(
            city=city,
            snap_output_path=snap_output_path,
            s2_reference_path=s2_reference_path,
            final_output_path=final_output_path,
            compress=compress,
            overwrite=overwrite,
        )

        for out in rows:
            out.update(
                {
                    "inventory_status": inventory_status,
                    "safe_path": safe_path_value,
                    "graph_path": str(graph_path),
                    "gpt_path": str(gpt_path),
                    "gpt_return_code": return_code,
                    "gpt_stdout_path": str(stdout_path),
                    "gpt_stderr_path": str(stderr_path),
                    "dem_name": dem_name,
                    "target_resolution": target_resolution,
                    "polarizations": polarizations,
                }
            )

        if not keep_snap_temp and snap_output_path.exists():
            snap_output_path.unlink(missing_ok=True)

        return rows

    except Exception as exc:
        out = dict(base_row)
        out.update(
            {
                "status": "FAILED_UNEXPECTED",
                "gpt_path": str(gpt_path) if gpt_path else "",
                "error": repr(exc),
            }
        )
        return [out]


def write_qc(rows: Sequence[Dict[str, Any]], qc_path: Path) -> None:
    ensure_dir(qc_path.parent)

    df = pd.DataFrame(rows)
    df.to_csv(qc_path, index=False)

    print(f"[INFO] Wrote QC CSV: {qc_path}")

    if "status" in df.columns:
        print("[INFO] Status counts:")
        print(df["status"].value_counts(dropna=False).to_string())

    if "city" in df.columns and "status" in df.columns:
        ok_cities = df.loc[df["status"] == "OK", "city"].nunique()
        print(f"[INFO] SNAP S1 cities successfully processed: {ok_cities}")


def main() -> int:
    args = parse_args()
    cfg = load_config(args.config)

    output_root = Path(str(cfg["output_root"]))

    safe_inventory_path = (
        args.safe_inventory
        if args.safe_inventory is not None
        else output_root / "metadata" / "s1_safe_inventory.csv"
    )

    qc_path = output_root / "qc" / "s1_snap_terrain_corrected_qc.csv"

    compress = bool(cfg.get("compress", True))
    overwrite = bool(cfg.get("overwrite", False)) or bool(args.overwrite)

    gpt_path = discover_gpt_path(cfg, args.gpt_path)

    print("[INFO] Sentinel-1 SNAP terrain-corrected preprocessing")
    print(f"[INFO] Script: {SCRIPT_NAME}")
    print(f"[INFO] Config: {args.config}")
    print(f"[INFO] Output root: {output_root}")
    print(f"[INFO] SAFE inventory: {safe_inventory_path}")
    print(f"[INFO] QC CSV: {qc_path}")
    print(f"[INFO] Compress: {compress}")
    print(f"[INFO] Overwrite: {overwrite}")
    print(f"[INFO] Dry run: {args.dry_run}")
    print(f"[INFO] GPT path: {gpt_path if gpt_path else 'NOT FOUND'}")
    print(f"[INFO] DEM name: {args.dem_name}")
    print(f"[INFO] Target resolution: {args.target_resolution}")
    print(f"[INFO] Polarizations: {args.polarizations}")

    inventory_df = load_safe_inventory(safe_inventory_path)
    inventory_df = filter_inventory(
        inventory_df,
        selected_cities=args.city,
        pilot_only=args.pilot_only,
    )

    print(f"[INFO] Cities selected from inventory: {len(inventory_df)}")

    all_rows: List[Dict[str, Any]] = []

    for _, row in tqdm(inventory_df.iterrows(), total=len(inventory_df), desc="SNAP S1 cities"):
        rows = process_city(
            row=row,
            output_root=output_root,
            gpt_path=gpt_path,
            compress=compress,
            overwrite=overwrite,
            dry_run=args.dry_run,
            keep_snap_temp=args.keep_snap_temp,
            dem_name=args.dem_name,
            target_resolution=args.target_resolution,
            polarizations=args.polarizations,
            snap_cache=args.snap_cache,
        )

        all_rows.extend(rows)

        city = normalize_city_name(row["city"])
        statuses = sorted(set(str(item.get("status")) for item in rows))
        print(f"[INFO] {city}: {', '.join(statuses)}")

    write_qc(all_rows, qc_path)

    statuses = {str(row.get("status")) for row in all_rows}

    if any(status.startswith("FAILED") for status in statuses):
        print("[ERROR] Some cities failed. Check the QC CSV and SNAP logs.")
        return 1

    if "OK" not in statuses:
        print("[WARN] No SNAP S1 products were created.")
        print("[WARN] This is expected if no SAFE products are available yet.")

    return 0


if __name__ == "__main__":
    raise SystemExit(main())