def format_float(x: object, digits: int = 4) -> str:
    try:
        if pd.isna(x):
            return ""
        return f"{float(x):.{digits}f}"
    except Exception:
        return str(x)


def make_compact_table_for_report(split_table: pd.DataFrame) -> pd.DataFrame:
    cols = [
        "split",
        "subset_label",
        "n_patches",
        "global_iou_favela",
        "global_dice_favela",
        "global_precision_favela",
        "global_recall_favela",
        "mean_gt_pos_pct",
        "mean_pred_pos_pct",
        "mean_pred_minus_gt_pct",
    ]

    compact = split_table[cols].copy()

    for col in [
        "global_iou_favela",
        "global_dice_favela",
        "global_precision_favela",
        "global_recall_favela",
        "mean_gt_pos_pct",
        "mean_pred_pos_pct",
        "mean_pred_minus_gt_pct",
    ]:
        compact[col] = compact[col].apply(lambda x: format_float(x, digits=4))

    return compact


def create_report(
    output_dir: Path,
    metrics_paths: Dict[str, str],
    split_table: pd.DataFrame,
    region_table: pd.DataFrame,
    city_table: pd.DataFrame,
) -> None:
    report_path = output_dir / "large_favela_upper_bound_report.md"

    lines: List[str] = []

    lines.append("# Large-Favela Upper-Bound Diagnostic")
    lines.append("")
    lines.append("## Objective")
    lines.append("")
    lines.append(
        "This diagnostic evaluates the existing baseline on progressively easier "
        "subsets of patches selected by ground-truth favela density."
    )
    lines.append("")
    lines.append("Main question:")
    lines.append("")
    lines.append("> At what favela-density threshold does the model become reliable?")
    lines.append("")
    lines.append("## Input metric files")
    lines.append("")

    for split, path in metrics_paths.items():
        lines.append(f"- **{split}**: `{path}`")

    lines.append("")
    lines.append("## Subset definitions")
    lines.append("")
    lines.append("| Subset | Definition |")
    lines.append("|:--|:--|")
    lines.append("| All patches | no filtering |")
    lines.append("| Positive patches | ground-truth favela percentage > 0% |")
    lines.append("| GT > 1% | ground-truth favela percentage > 1% |")
    lines.append("| GT > 5% | ground-truth favela percentage > 5% |")
    lines.append("| GT > 10% | ground-truth favela percentage > 10% |")
    lines.append("| GT > 20% | ground-truth favela percentage > 20% |")
    lines.append("| GT > 40% | ground-truth favela percentage > 40% |")

    lines.append("")
    lines.append("## Main split-level results")
    lines.append("")

    compact = make_compact_table_for_report(split_table)
    lines.append(compact.to_markdown(index=False))

    lines.append("")
    lines.append("## Interpretation guide")
    lines.append("")
    lines.append(
        "- If performance improves strongly as GT threshold increases, then large "
        "continuous favela regions are easier and the full task is dominated by "
        "tiny/sparse/ambiguous patches."
    )
    lines.append(
        "- If train improves but validation/test remain weak, then the model is "
        "learning training-city morphology but not generalizing robustly."
    )
    lines.append(
        "- If precision improves but recall drops at high thresholds, the model is "
        "too conservative on large unseen favela regions."
    )
    lines.append(
        "- If predicted favela percentage is much larger than GT percentage, the "
        "model is overpredicting and hard-negative mining is needed."
    )
    lines.append(
        "- If predicted favela percentage is much smaller than GT percentage, the "
        "model is underpredicting and may be missing large labelled regions."
    )

    lines.append("")
    lines.append("## Useful output files")
    lines.append("")
    lines.append("- `csv/large_favela_upper_bound_by_split.csv`")
    lines.append("- `csv/large_favela_upper_bound_by_region.csv`")
    lines.append("- `csv/large_favela_upper_bound_by_city.csv`")
    lines.append("- `csv/large_favela_upper_bound_enriched_per_patch.csv`")
    lines.append("- `figures/upper_bound_iou_by_threshold.png`")
    lines.append("- `figures/upper_bound_precision_by_threshold.png`")
    lines.append("- `figures/upper_bound_recall_by_threshold.png`")
    lines.append("- `figures/upper_bound_pred_minus_gt_by_threshold.png`")

    report_path.write_text("\n".join(lines), encoding="utf-8")


def main() -> None:
    args = parse_args()

    run_dir: Path = args.run_dir
    output_dir: Path = (
        args.output_dir
        if args.output_dir is not None
        else run_dir / "large_favela_upper_bound_224"
    )

    prepare_output_dir(output_dir, overwrite=args.overwrite)

    all_df, metrics_paths = read_all_splits(
        run_dir=run_dir,
        splits=args.splits,
        threshold_tag=args.threshold_tag,
    )

    split_table, region_table, city_table = build_upper_bound_tables(all_df)

    csv_dir = output_dir / "csv"

    all_df.to_csv(
        csv_dir / "large_favela_upper_bound_enriched_per_patch.csv",
        index=False,
    )

    split_table.to_csv(
        csv_dir / "large_favela_upper_bound_by_split.csv",
        index=False,
    )

    region_table.to_csv(
        csv_dir / "large_favela_upper_bound_by_region.csv",
        index=False,
    )

    city_table.to_csv(
        csv_dir / "large_favela_upper_bound_by_city.csv",
        index=False,
    )

    save_figures(
        split_table=split_table,
        city_table=city_table,
        output_dir=output_dir,
        splits=args.splits,
        min_city_patches=args.min_city_patches,
    )

    metadata = {
        "run_dir": str(run_dir),
        "output_dir": str(output_dir),
        "splits": args.splits,
        "metrics_paths": metrics_paths,
        "subset_definitions": [
            {
                "subset": name,
                "label": SUBSET_LABELS[name],
                "gt_threshold_pct": threshold,
            }
            for name, threshold in SUBSET_DEFINITIONS
        ],
        "min_city_patches": args.min_city_patches,
    }

    with (output_dir / "metadata.json").open("w", encoding="utf-8") as f:
        json.dump(metadata, f, indent=2)

    create_report(
        output_dir=output_dir,
        metrics_paths=metrics_paths,
        split_table=split_table,
        region_table=region_table,
        city_table=city_table,
    )

    print("\nDone. Large-favela upper-bound diagnostics written to:")
    print(f"  {output_dir}")

    print("\nMain files:")
    print(f"  {output_dir / 'large_favela_upper_bound_report.md'}")
    print(f"  {output_dir / 'csv' / 'large_favela_upper_bound_by_split.csv'}")
    print(f"  {output_dir / 'csv' / 'large_favela_upper_bound_by_region.csv'}")
    print(f"  {output_dir / 'csv' / 'large_favela_upper_bound_by_city.csv'}")
    print(f"  {output_dir / 'figures'}")

    print("\nSplit-level summary:")
    compact = make_compact_table_for_report(split_table)
    print(compact.to_string(index=False))


if __name__ == "__main__":
    main()