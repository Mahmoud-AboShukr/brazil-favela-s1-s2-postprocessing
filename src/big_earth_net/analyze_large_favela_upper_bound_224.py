"""
Large-favela upper-bound diagnostic for reBEN/UPerNet favela segmentation.

Purpose
-------
This script evaluates the already-trained baseline on progressively easier
subsets of patches, selected by ground-truth favela density.

It answers:

    At what favela-density threshold does the model become reliable?

The script reads per-patch metrics generated by:

    src/big_earth_net/visualize_reben_predictions_224.py

Expected input files:

    <run-dir>/visual_predictions/train_best_thr0p450/per_patch_metrics_train.csv
    <run-dir>/visual_predictions/val_best_thr0p450/per_patch_metrics_val.csv
    <run-dir>/visual_predictions/test_best_thr0p450/per_patch_metrics_test.csv

Main outputs:

    <run-dir>/large_favela_upper_bound_224/
        large_favela_upper_bound_report.md
        metadata.json
        csv/
            large_favela_upper_bound_by_split.csv
            large_favela_upper_bound_by_region.csv
            large_favela_upper_bound_by_city.csv
            large_favela_upper_bound_enriched_per_patch.csv
        figures/
            upper_bound_iou_by_threshold.png
            upper_bound_dice_by_threshold.png
            upper_bound_precision_by_threshold.png
            upper_bound_recall_by_threshold.png
            upper_bound_pred_minus_gt_by_threshold.png
            upper_bound_patch_count_by_threshold.png
            upper_bound_mean_gt_pred_by_threshold_<split>.png
            upper_bound_city_iou_gt10_<split>.png
            upper_bound_city_iou_gt20_<split>.png

Author: Mahmoud Abo Shukr
"""

