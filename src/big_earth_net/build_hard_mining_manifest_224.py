def main() -> None:
    args = parse_args()

    run_dir: Path = args.run_dir
    output_dir: Path = (
        args.output_dir
        if args.output_dir is not None
        else run_dir / "hard_mining_manifest_224"
    )

    prepare_output_dir(output_dir=output_dir, overwrite=args.overwrite)

    all_df, metrics_paths = read_all_splits(
        run_dir=run_dir,
        splits=args.splits,
        threshold_tag=args.threshold_tag,
    )

    csv_dir = output_dir / "csv"
    figures_dir = output_dir / "figures"

    all_df.to_csv(
        csv_dir / "all_splits_hard_mining_enriched.csv",
        index=False,
    )

    train_df = all_df[all_df["split"] == "train"].copy()

    if len(train_df) == 0:
        raise ValueError(
            "No train rows found. Cannot build training hard-mining manifests."
        )

    train_counts = save_train_pool_csvs(
        train_df=train_df,
        csv_dir=csv_dir,
    )

    pool_summary_by_split = build_pool_summary(
        df=all_df,
        group_cols=["split"],
        pool_names=TRAIN_POOL_EXPORTS,
    )

    pool_summary_by_split.to_csv(
        csv_dir / "diagnostic_pool_summary_by_split.csv",
        index=False,
    )

    pool_summary_by_split_city = build_pool_summary(
        df=all_df,
        group_cols=["split", "region", "city"],
        pool_names=TRAIN_POOL_EXPORTS,
    )

    pool_summary_by_split_city.to_csv(
        csv_dir / "diagnostic_pool_summary_by_split_city.csv",
        index=False,
    )

    target_size = args.target_size if args.target_size is not None else len(train_df)

    curriculum_summary = save_curriculum_manifests(
        train_df=train_df,
        csv_dir=csv_dir,
        target_size=target_size,
        seed=args.seed,
    )

    save_figures(
        all_df=all_df,
        train_df=train_df,
        pool_summary_by_split=pool_summary_by_split,
        curriculum_summary=curriculum_summary,
        figures_dir=figures_dir,
    )

    metadata = {
        "run_dir": str(run_dir),
        "output_dir": str(output_dir),
        "splits": args.splits,
        "metrics_paths": metrics_paths,
        "pool_definitions": POOL_DEFINITIONS,
        "curriculum_recipes": CURRICULUM_RECIPES,
        "target_size": int(target_size),
        "seed": int(args.seed),
        "important_note": (
            "Training manifests are built from train split only. "
            "Validation/test hard pools are diagnostic only and must not be used for training."
        ),
    }

    with (output_dir / "metadata.json").open("w", encoding="utf-8") as f:
        json.dump(metadata, f, indent=2)

    create_report(
        output_dir=output_dir,
        metrics_paths=metrics_paths,
        train_counts=train_counts,
        pool_summary_by_split=pool_summary_by_split,
        pool_summary_by_split_city=pool_summary_by_split_city,
        curriculum_summary=curriculum_summary,
    )

    print("\nDone. Hard-mining manifests written to:")
    print(f"  {output_dir}")

    print("\nMain report:")
    print(f"  {output_dir / 'hard_mining_report.md'}")

    print("\nTrain pool counts:")
    for pool_name, count in train_counts.items():
        print(f"  {pool_name:32s}: {count}")

    print("\nCurriculum manifests:")
    for recipe_name, summary in curriculum_summary.items():
        print(
            f"  {recipe_name:16s}: "
            f"sampled={summary['n_rows_sampled_manifest']}, "
            f"unique={summary['n_rows_unique_manifest']}"
        )

    print("\nImportant note:")
    print("  Use only train_* CSVs for training. Val/test pools are diagnostic only.")


if __name__ == "__main__":
    main()