"""
Build hard-mining manifests for the reBEN/UPerNet favela segmentation baseline.

Purpose
-------
This script uses the per-patch metrics generated by the visualisation/diagnostic
pipeline to create hard-mining pools for the next training stage.

It creates pools for:

    1. hard negatives
       - low GT favela percentage
       - high predicted favela percentage

    2. missed large positives
       - high GT favela percentage
       - low recall or strong underprediction

    3. good large positives
       - high GT favela percentage
       - good IoU

    4. random negatives
       - no GT favela
       - almost no predicted favela

    5. medium/large positives
       - GT favela percentage >= 5%

Important rule
--------------
Training manifests are built ONLY from the train split to avoid validation/test
leakage. Validation/test pools are exported only for diagnostics.

Expected input files
--------------------
<run-dir>/visual_predictions/train_best_thr0p450/per_patch_metrics_train.csv
<run-dir>/visual_predictions/val_best_thr0p450/per_patch_metrics_val.csv
<run-dir>/visual_predictions/test_best_thr0p450/per_patch_metrics_test.csv

Main outputs
------------
<run-dir>/hard_mining_manifest_224/
    metadata.json
    hard_mining_report.md

    csv/
        all_splits_hard_mining_enriched.csv

        train_hard_negative_strict.csv
        train_hard_negative_moderate.csv
        train_missed_large_positive.csv
        train_severe_missed_large_positive.csv
        train_good_large_positive.csv
        train_medium_large_positive.csv
        train_random_negative.csv

        diagnostic_pool_summary_by_split.csv
        diagnostic_pool_summary_by_split_city.csv

        train_curriculum_manifest_balanced_v1.csv
        train_curriculum_manifest_balanced_v1_unique.csv
        train_curriculum_manifest_conservative_v1.csv
        train_curriculum_manifest_conservative_v1_unique.csv

    figures/
        train_pool_counts.png
        diagnostic_pool_counts_by_split.png
        train_pool_counts_by_city.png
        curriculum_manifest_composition.png

Author: Mahmoud Abo Shukr
"""

