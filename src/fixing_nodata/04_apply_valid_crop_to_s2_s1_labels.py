#!/usr/bin/env python3
"""
Apply valid crop windows to S2, S1 SNAP, and final label rasters.

This creates a new cropped dataset instance where border-connected S2 nodata
has been removed according to crop windows computed by:

    03_compute_s2_valid_crop_windows.py

Important:
- This script physically writes new rasters.
- It applies the exact same pixel window to S2, S1, and labels.
- It does not fill remaining internal S2 nodata.
- It creates a crop-based repaired instance, so label loss must be documented.
"""

from __future__ import annotations

import argparse
import csv
import json
import shutil
from pathlib import Path

import numpy as np
import pandas as pd
import rasterio
from rasterio.windows import Window


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Apply valid crop windows to aligned S2, S1 SNAP, and label rasters."
    )

    parser.add_argument(
        "--crop-windows",
        type=str,
        required=True,
        help="CSV generated by 03_compute_s2_valid_crop_windows.py.",
    )

    parser.add_argument(
        "--s2-root",
        type=str,
        required=True,
        help="Input S2 root, e.g. D:/post_processing_dataset/dataset_instances/instance_B_standard_rs/s2",
    )

    parser.add_argument(
        "--s1-root",
        type=str,
        required=True,
        help="Input S1 SNAP root, e.g. D:/post_processing_dataset/dataset_instances/instance_B_standard_rs/s1_snap",
    )

    parser.add_argument(
        "--labels-root",
        type=str,
        required=True,
        help="Input labels root, e.g. D:/post_processing_dataset/labels_final",
    )

    parser.add_argument(
        "--output-root",
        type=str,
        required=True,
        help=(
            "Output instance root, e.g. "
            "D:/post_processing_dataset/dataset_instances/instance_C_s2_nodata_repaired"
        ),
    )

    parser.add_argument(
        "--cities",
        nargs="*",
        default=None,
        help="Optional city list. If omitted, all cities in crop-window CSV are processed.",
    )

    parser.add_argument(
        "--tile-size",
        type=int,
        default=512,
        help="Chunk size for block-wise raster copying.",
    )

    parser.add_argument(
        "--overwrite",
        action="store_true",
        help="Overwrite existing output rasters.",
    )

    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Only print planned operations; do not write files.",
    )

    return parser.parse_args()


def find_s2_raster(root: Path, city: str) -> Path:
    patterns = [
        root / city / f"{city}_s2_12bands_reflectance_10m.tif",
        root / city / f"{city}_s2*.tif",
        root / f"{city}_s2_12bands_reflectance_10m.tif",
    ]

    candidates: list[Path] = []

    for pattern in patterns:
        if "*" in str(pattern):
            candidates.extend(sorted(pattern.parent.glob(pattern.name)))
        elif pattern.exists():
            candidates.append(pattern)

    candidates = [p for p in candidates if p.is_file() and city in p.name]

    if not candidates:
        raise FileNotFoundError(f"No S2 raster found for {city} under {root}")

    exact = [p for p in candidates if p.name == f"{city}_s2_12bands_reflectance_10m.tif"]
    return exact[0] if exact else candidates[0]


